export type Lang = 'zh' | 'en';
export const langs: Lang[] = ['zh', 'en'];

const base = import.meta.env.BASE_URL.replace(/\/?$/, '/');

/** 產生站內網址；path 不需要開頭的斜線 */
export function url(lang: Lang, path = ''): string {
  const p = path.replace(/^\//, '');
  return `${base}${lang === 'en' ? 'en/' : ''}${p}`;
}

