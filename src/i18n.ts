export function formatDate(d: Date, lang: Lang): string {
  return d.toLocaleDateString(lang === 'zh' ? 'zh-TW' : 'en-CA', { year: 'numeric', month: '2-digit', day: '2-digit', timeZone: 'Asia/Taipei' }).replace(/\//g, '-');
}
